'use strict';
const path = require('path');
const fs = require('fs');
const { AsyncLocalStorage } = require('async_hooks');
const { Pool, types } = require('pg');

const DATA_DIR = path.resolve(process.env.DATA_DIR || path.join(__dirname, '..', 'data'));
const MEDIA_DIR = path.join(DATA_DIR, 'media');
fs.mkdirSync(MEDIA_DIR, { recursive: true });
if (!process.env.DATABASE_URL) throw new Error('Задайте DATABASE_URL для PostgreSQL');
types.setTypeParser(20, Number); // BIGINT: миллисекунды времени и COUNT(*)
const pool = new Pool({
  connectionString: process.env.DATABASE_URL,
  ssl: /(?:supabase\.co|pooler\.supabase\.com)/.test(process.env.DATABASE_URL) ? { rejectUnauthorized: false } : false,
  max: 10,
  connectionTimeoutMillis: 10000,
});
const scope = new AsyncLocalStorage();

function compile(sql, args) {
  let values = [];
  const statement = sql.replace(/\bINSERT OR IGNORE\b/gi, 'INSERT');
  let compiled;
  if (args.length === 1 && args[0] && typeof args[0] === 'object' && !Array.isArray(args[0])) {
    const params = args[0];
    const names = new Map();
    compiled = statement.replace(/@([a-z_][a-z_0-9]*)/gi, (_, name) => {
      if (!Object.hasOwn(params, name)) throw new Error(`Отсутствует параметр SQL: ${name}`);
      if (!names.has(name)) { values.push(params[name]); names.set(name, values.length); }
      return `$${names.get(name)}`;
    });
  } else {
    values = args;
    let n = 0;
    compiled = statement.replace(/\?/g, () => `$${++n}`);
    if (n !== values.length) throw new Error(`Число параметров SQL: ожидалось ${n}, получено ${values.length}`);
  }
  if (/\bINSERT OR IGNORE\b/i.test(sql)) compiled += ' ON CONFLICT DO NOTHING';
  return { text: compiled, values };
}
async function query(sql, args = []) {
  const { text, values } = compile(sql, args);
  return (scope.getStore() || pool).query(text, values);
}
const db = {
  prepare(sql) {
    const run = async (...args) => {
      let q = sql;
      if (/^\s*INSERT INTO (instances|lists|campaigns|templates)\b/i.test(q) && !/\bRETURNING\b/i.test(q)) q += ' RETURNING id';
      const r = await query(q, args);
      return { changes: r.rowCount, lastInsertRowid: r.rows[0]?.id };
    };
    return {
      run,
      get: async (...args) => (await query(sql, args)).rows[0],
      all: async (...args) => (await query(sql, args)).rows,
    };
  },
  transaction(fn) {
    return async (...args) => {
      const client = await pool.connect();
      try {
        await client.query('BEGIN');
        const result = await scope.run(client, () => fn(...args));
        await client.query('COMMIT');
        return result;
      } catch (e) {
        await client.query('ROLLBACK');
        throw e;
      } finally { client.release(); }
    };
  },
  close: () => pool.end(),
};

async function initDb() {
  await pool.query(`
CREATE TABLE IF NOT EXISTS instances (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL, id_instance TEXT NOT NULL UNIQUE, api_token TEXT NOT NULL, api_url TEXT NOT NULL,
  state TEXT NOT NULL DEFAULT 'unknown', phone TEXT, enabled INTEGER NOT NULL DEFAULT 1,
  disabled_reason TEXT, daily_limit_start INTEGER NOT NULL DEFAULT 50, daily_limit_max INTEGER NOT NULL DEFAULT 500,
  warmup_step INTEGER NOT NULL DEFAULT 30, first_send_day TEXT, created_at BIGINT NOT NULL,
  managed INTEGER NOT NULL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS lists (id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name TEXT NOT NULL, created_at BIGINT NOT NULL);
CREATE TABLE IF NOT EXISTS contacts (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, phone TEXT NOT NULL UNIQUE,
  name TEXT NOT NULL DEFAULT '', vars TEXT NOT NULL DEFAULT '{}',
  opted_out INTEGER NOT NULL DEFAULT 0, opted_out_at BIGINT
);
CREATE INDEX IF NOT EXISTS contacts_opted ON contacts(opted_out) WHERE opted_out = 1;
CREATE TABLE IF NOT EXISTS list_contacts (list_id INTEGER NOT NULL, contact_id INTEGER NOT NULL, PRIMARY KEY (list_id, contact_id));
CREATE INDEX IF NOT EXISTS list_contacts_contact ON list_contacts(contact_id);
CREATE TABLE IF NOT EXISTS campaigns (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name TEXT NOT NULL, text TEXT NOT NULL DEFAULT '',
  media_url TEXT, media_name TEXT, list_id INTEGER, instance_ids TEXT NOT NULL DEFAULT '[]',
  status TEXT NOT NULL DEFAULT 'draft', delay_min INTEGER NOT NULL DEFAULT 120, delay_max INTEGER NOT NULL DEFAULT 240,
  hour_from INTEGER NOT NULL DEFAULT 10, hour_to INTEGER NOT NULL DEFAULT 20, check_wa INTEGER NOT NULL DEFAULT 0,
  created_at BIGINT NOT NULL, started_at BIGINT, finished_at BIGINT
);
CREATE TABLE IF NOT EXISTS messages (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, campaign_id INTEGER NOT NULL,
  contact_id INTEGER NOT NULL, phone TEXT NOT NULL, status TEXT NOT NULL DEFAULT 'pending',
  instance_id INTEGER, id_message TEXT, text TEXT, error TEXT, replied INTEGER NOT NULL DEFAULT 0,
  sent_at BIGINT, UNIQUE (campaign_id, contact_id)
);
CREATE INDEX IF NOT EXISTS messages_queue ON messages(campaign_id, status, id);
CREATE INDEX IF NOT EXISTS messages_idmsg ON messages(id_message) WHERE id_message IS NOT NULL;
CREATE INDEX IF NOT EXISTS messages_phone ON messages(phone, sent_at);
CREATE INDEX IF NOT EXISTS messages_contact ON messages(contact_id, sent_at);
CREATE TABLE IF NOT EXISTS daily_counts (
  instance_id INTEGER NOT NULL, day TEXT NOT NULL, count INTEGER NOT NULL DEFAULT 0,
  PRIMARY KEY (instance_id, day)
);
CREATE TABLE IF NOT EXISTS incoming (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, instance_id INTEGER, phone TEXT NOT NULL,
  name TEXT, text TEXT, is_stop INTEGER NOT NULL DEFAULT 0, created_at BIGINT NOT NULL
);
CREATE TABLE IF NOT EXISTS events (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, ts BIGINT NOT NULL,
  level TEXT NOT NULL DEFAULT 'info', instance_id INTEGER, message TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS templates (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name TEXT NOT NULL, text TEXT NOT NULL, created_at BIGINT NOT NULL
);
CREATE TABLE IF NOT EXISTS settings (key TEXT PRIMARY KEY, value TEXT NOT NULL);
`);
  // дополнительные варианты текста рассылки: каждому получателю уходит один из вариантов
  await query("ALTER TABLE campaigns ADD COLUMN IF NOT EXISTS extra_texts TEXT NOT NULL DEFAULT '[]'");
  await query('INSERT INTO settings(key, value) VALUES (?, ?) ON CONFLICT DO NOTHING',
    ['stop_words', 'стоп, stop, отписка, отписаться, отпишите, не пишите, unsubscribe']);
  await db.transaction(async () => {
    if (await db.prepare("SELECT 1 FROM settings WHERE key = 'templates_seeded'").get()) return;
    const stop = '\n\nОтветьте СТОП, чтобы отписаться.';
    const seed = [
      ['Акция или спецпредложение', '{Здравствуйте|Добрый день}, {name}!\n\n{Хотим рассказать|Рады сообщить} о специальном предложении: [что предлагаете и до какого числа].\n\n{Интересно? Напишите «да» — расскажем подробнее|Ответьте на это сообщение, и мы всё расскажем}.' + stop],
      ['Напоминание', '{Здравствуйте|Добрый день}, {name}!\n\nНапоминаем: [о чём напоминаете].\n\n{Если есть вопросы — просто ответьте на это сообщение|Будут вопросы — напишите нам сюда}.' + stop],
      ['Возвращение клиента', '{Здравствуйте|Добрый день}, {name}!\n\n{Давно вас не видели|Вы давно у нас не были} — {хотим пригласить вас снова|будем рады видеть вас снова}. [Что нового или какой бонус].\n\n{Записать вас?|Подобрать удобное время?}' + stop],
    ];
    for (const [name, text] of seed) await db.prepare('INSERT INTO templates(name, text, created_at) VALUES (?, ?, ?)').run(name, text, Date.now());
    await query("INSERT INTO settings(key, value) VALUES ('templates_seeded', '1') ON CONFLICT DO NOTHING");
  })();
  // разовый перевод незавершённых рассылок на перерыв 2–4 минуты между сообщениями
  await db.transaction(async () => {
    if (await db.prepare("SELECT 1 FROM settings WHERE key = 'pause_minutes_v1'").get()) return;
    await query("UPDATE campaigns SET delay_min = 120, delay_max = 240 WHERE status IN ('draft', 'running', 'paused')");
    await query("INSERT INTO settings(key, value) VALUES ('pause_minutes_v1', '1') ON CONFLICT DO NOTHING");
  })();
}
async function logEvent(message, level = 'info', instanceId = null) {
  await db.prepare('INSERT INTO events(ts, level, instance_id, message) VALUES (?, ?, ?, ?)')
    .run(Date.now(), level, instanceId, String(message).slice(0, 1000));
  if (level !== 'info') console.log(`[${level}] ${message}`);
}
async function getSetting(key, fallback = '') {
  const r = await db.prepare('SELECT value FROM settings WHERE key = ?').get(key);
  return r ? r.value : fallback;
}
async function setSetting(key, value) {
  await db.prepare('INSERT INTO settings(key, value) VALUES (?, ?) ON CONFLICT(key) DO UPDATE SET value = excluded.value').run(key, String(value));
}
module.exports = { db, initDb, DATA_DIR, MEDIA_DIR, logEvent, getSetting, setSetting };
